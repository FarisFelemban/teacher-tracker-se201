CREATE TABLE IF NOT EXISTS user_account (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 email VARCHAR(254) NOT NULL UNIQUE,
 password_hash VARCHAR(100) NOT NULL,
 role VARCHAR(10) NOT NULL CHECK (role IN ('TEACHER','ADMIN'))
);
CREATE TABLE IF NOT EXISTS school (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(120) NOT NULL,
 city VARCHAR(120) NOT NULL
);
CREATE TABLE IF NOT EXISTS teacher_profile (
 account_id BIGINT PRIMARY KEY REFERENCES user_account(id) ON DELETE CASCADE,
 name VARCHAR(120) NOT NULL,
 school_id BIGINT NOT NULL REFERENCES school(id),
 application_message VARCHAR(2000) NOT NULL,
 status VARCHAR(10) NOT NULL CHECK (status IN ('PENDING','APPROVED','REJECTED')),
 feedback VARCHAR(2000) NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS admission_settings (
 id INTEGER PRIMARY KEY CHECK (id=1),
 max_active INTEGER NOT NULL CHECK (max_active BETWEEN 1 AND 1000),
 inactivity_seconds INTEGER NOT NULL CHECK (inactivity_seconds BETWEEN 10 AND 3600),
 queue_capacity INTEGER NOT NULL CHECK (queue_capacity BETWEEN 1 AND 1000)
);

